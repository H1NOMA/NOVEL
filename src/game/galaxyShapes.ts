export const DEFAULT_SHAPE: GalaxyShape = 'disc';

export function shapeDef(id: GalaxyShape | undefined): GalaxyShapeDef {
  return GALAXY_SHAPES.find((s) => s.id === id) ?? GALAXY_SHAPES[0]!;
}

/** Нормировать угол в [0, 2π). */
export function normAngle(a: number): number {
  let x = a % TAU;
  if (x < 0) x += TAU;
  return x;
}
