// ---------------------------------------------------------------------------
// Формы галактики.
//
// Партия начинается с выбора того, как вообще устроен театр военных действий.
// Форма меняет не декорацию, а стратегию: в спирали рукава образуют длинные
// уязвимые коридоры, в кольце пустое ядро отрезает центр от периферии, в
// скоплениях война идёт за узкие перешейки между островами.
//
// ВАЖНОЕ ОГРАНИЧЕНИЕ, которое соблюдает каждая форма: сектора по-прежнему
// накрывают полный круг. Домашние клинья фракций назначаются по углу, и если
// в каком-то направлении не окажется ни одной планеты, фракция останется без
// столицы и просто исчезнет из партии. Поэтому форма задаёт ПЛОТНОСТЬ по углу
// и радиусу, а не вырезает куски карты.
// ---------------------------------------------------------------------------

export type GalaxyShape = 'disc' | 'spiral' | 'ring' | 'clusters' | 'bar';

export interface GalaxyShapeDef {
  id: GalaxyShape;
  label: string;
  blurb: string;
  /** Поворот кольца относительно предыдущего (радианы) — закрутка рукавов. */
  twist: number;
  /** Множитель радиуса кольца: >1 отодвигает его от центра. */
  radial(ring: number): number;
  /** Множитель числа планет в кольце. */
  density(ring: number): number;
  /** Плотность по углу внутри кольца: 1 — как в диске, 0.2 — почти пусто. */
  weight(angle: number, ring: number): number;
}

const TAU = Math.PI * 2;

/** Две спиральные ветви: гребень плотности, закрученный вместе с кольцами. */
function arms(angle: number, ring: number, count: number, tight: number, sharp: number): number {
  const phase = angle - ring * tight;
  // cos с удвоенной (или утроенной) частотой даёт нужное число гребней.
  const ridge = Math.cos(phase * count) * 0.5 + 0.5;
  return 0.22 + 1.9 * Math.pow(ridge, sharp);
}

