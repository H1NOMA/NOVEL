interface NameRng {
  int(a: number, b: number): number;
  pick<T>(a: readonly T[]): T;
  chance(p: number): boolean;
  shuffle<T>(a: T[]): void;
}

/**
 * Раздатчик имён на одну галактику. Канон перемешивается один раз и выдаётся
 * по порядку — так каждая партия начинается с разных знакомых миров, но в
 * пределах одного сида карта неизменна.
 */
export function nameSource(rng: NameRng, used: Set<string>): () => string {
  const pool = [...CANON];
  rng.shuffle(pool);
  let next = 0;
  return () => {
    while (next < pool.length) {
      const n = pool[next++]!;
      if (!used.has(n)) {
        used.add(n);
        return n;
      }
    }
    return proceduralName(rng, used);
  };
}

/** Имя по каноничным правилам — когда настоящие миры кончились. */
function proceduralName(rng: NameRng, used: Set<string>): string {
  for (let attempt = 0; attempt < 40; attempt++) {
    const root = rng.pick(ROOTS);
    const name = rng.chance(0.62) ? `${root} ${rng.pick(TAILS)}` : root;
    if (!used.has(name)) {
      used.add(name);
      return name;
    }
  }
  const fallback = `${rng.pick(ROOTS)} ${rng.int(2, 99)}`;
  used.add(fallback);
  return fallback;
}

