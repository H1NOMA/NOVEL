import logoUrl from '../assets/menulogo.webp?url';

// ---------------------------------------------------------------------------
// Логотип главного меню.
//
// Растр лежит в src/assets/menulogo.webp — прозрачный PNG, прогнанный через
// tools/images/enhance.py (чистка маски, апскейл, аншарп). Vite вшивает его в
// сборку и выдаёт готовый URL, поэтому внешних загрузок в рантайме нет.
//
// Ширина знака задаётся в rem и потому едет вместе с масштабом интерфейса.
// ---------------------------------------------------------------------------

/** Логотип целиком: знак и подпись-хвост под ним. */
export function logoBlock(): string {
  return `<div class="logo">
    <img class="logo-mark" src="${logoUrl}" alt="Вторая Галактическая война" draggable="false">
  </div>`;
}
